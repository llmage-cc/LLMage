#!/usr/bin/env bash
# check-serial-uid-drift.sh — pre-commit / CI gate against replay-orphaning serialVersionUID drift
# (third instance of the class: Deck 2026-09-17, ManaCostImpl+HumanPlayer 2026-09-29 —
# see  §"Recommended fix").
#
# Two phases:
#
#   PHASE 1 [always]: inventory every Serializable class in the target modules using the JVM's OWN
#     oracle (scripts/SerialOracle.java — ObjectStreamClass over target/classes, so TRANSITIVE
#     Serializable like ManaCostImpl→CostImpl→Cost→Serializable is caught; the literal-source grep
#     that missed exactly that case is the FALLBACK only). Any Serializable class with NO pinned
#     serialVersionUID and no row in scripts/serial-uid-allowlist.txt ⇒ FAIL.
#
#   PHASE 2 [--changed BASE]: for every CHANGED Serializable class vs BASE that HAS a pin, verify the
#     pin still matches the JVM-computed UID. Mismatch ⇒ FAIL (the commit would invalidate saves).
#
# Usage:
#   scripts/check-serial-uid-drift.sh                     # phase 1
#   scripts/check-serial-uid-drift.sh --changed [BASE]    # + phase 2 (default origin/master)
#   scripts/check-serial-uid-drift.sh --update-allowlist  # regenerate scripts/serial-uid-allowlist.txt
#   bash scripts/gen-serial-oracle-cp.sh                  # refresh /tmp/serial-oracle-cp.txt (deps CP)
#
# Exit codes: 0 = pass, 1 = violations found, 2 = usage/build error.
# Requires: JDK (javac/java), grep. No server, no network.
set -euo pipefail
cd "$(dirname "$0")/.."
WT="$(pwd)"

MODULES=(
  Mage
  Mage.Common
  Mage.Server
  Mage.Server.Plugins/Mage.Player.AI
  Mage.Server.Plugins/Mage.Player.LLM
  Mage.Server.Plugins/Mage.Player.Human
)

ALLOWLIST="scripts/serial-uid-allowlist.txt"
ORACLE_BIN="scripts/.SerialOracle.bin"
DEP_CP_FILE="scripts/.serial-oracle-cp.txt"

build_classpath() {
  local cp="" mod
  for mod in "${MODULES[@]}"; do
    [ -d "$mod/target/classes" ] && cp="$cp:$WT/$mod/target/classes"
  done
  [ -f "$DEP_CP_FILE" ] && cp="$cp:$(cat "$DEP_CP_FILE")"
  echo "$cp"
}

# Prints "<fqn> <uid>" lines for classes that ARE Serializable; rc 9 = oracle unavailable (fallback).
run_oracle() {
  local cp bin="$ORACLE_BIN"
  cp="$(build_classpath)"
  [ -n "$cp" ] || return 9
  [ -d "$bin" ] || { javac -nowarn -cp "$cp" -d "$bin" scripts/SerialOracle.java 2>/dev/null || return 9; }
  java -cp "$cp:$bin" SerialOracle 2>/dev/null
}

# Source-level fallback inventory: literal "implements ... Serializable" only (NON-transitive blind).
literal_serializable_files() {
  for mod in "${MODULES[@]}"; do
    [ -d "$mod/src/main/java" ] || continue
    grep -rl "implements[[:space:]].*Serializable\|implements[[:space:]]*Serializable" \
      "$mod/src/main/java" --include="*.java" 2>/dev/null
  done
}

# dotted-class inventory from the built tree (oracle input)
oracle_inventory() {
  local mod f cls
  for mod in "${MODULES[@]}"; do
    [ -d "$mod/target/classes" ] || continue
    find "$mod/target/classes" -name '*.class' ! -name '*$*' 2>/dev/null | while read -r f; do
      cls="${f#"$mod/target/classes/"}"; cls="${cls%.class}"; cls="${cls//\//.}"
      echo "$cls"
    done
  done
}

class_to_src() { # dotted fqn -> repo-relative .java path (first module hit)
  local rel="${1//.//}.java" mod
  for mod in "${MODULES[@]}"; do
    if [ -f "$mod/src/main/java/$rel" ]; then echo "$mod/src/main/java/$rel"; return 0; fi
  done
  return 1
}

mode=check
changed_base=""
while [ $# -gt 0 ]; do
  case "$1" in
    --changed) mode=changed; changed_base="${2:-origin/master}"; shift 2 ;;
    --update-allowlist) mode=allowlist; shift ;;
    -h|--help) sed -n '2,24p' "$0"; exit 0 ;;
    *) echo "ERROR: unknown argument: $1" >&2; exit 2 ;;
  esac
done

unpinned_tmp="$(mktemp)"
serial_all_srcs="$(mktemp)"
trap 'rm -f "$unpinned_tmp" "$serial_all_srcs"' EXIT

# ---- Phase 1 ----
if run_oracle > /tmp/serial-oracle-out.txt < <(oracle_inventory); then
  # oracle rows: "<fqn> <uid>"; uid is the COMPUTED value — pinned classes appear with their pin.
  awk '{print $1}' /tmp/serial-oracle-out.txt | sort -u | while read -r cls; do
    src="$(class_to_src "$cls")" && echo "$src" || true
  done > "$serial_all_srcs"
  sort -u "$serial_all_srcs" | while read -r f; do
    grep -L "serialVersionUID" "$f" || true
  done > "$unpinned_tmp"
else
  echo "NOTE: SerialOracle unavailable (no target/classes / deps CP missing) — literal grep fallback (NON-transitive blind: see ManaCostImpl 09-29)." >&2
  literal_serializable_files | sort -u | while read -r f; do
    grep -L "serialVersionUID" "$f" || true
  done > "$unpinned_tmp"
fi
unpinned_count=$(wc -l < "$unpinned_tmp")

if [ "$mode" = allowlist ]; then
  { echo "# serial-uid-allowlist — Serializable classes with NO pinned serialVersionUID."
    echo "# Generated by: scripts/check-serial-uid-drift.sh --update-allowlist"
    echo "# KEEP THIS LIST SHORT. Every row is a class that will silently orphan old"
    echo "# .game saves if it (or its superclass chain) is ever edited."
    echo "# The FIX for a drifted class is: pin the PRE-drift stream value with a comment"
    echo "# naming the incident, then remove the row here (see Deck.java, ManaCostImpl,"
    echo "# HumanPlayer pins of 2026-09-30)."
    sort -u "$unpinned_tmp"
  } > "$ALLOWLIST"
  echo "Allowlist regenerated: $ALLOWLIST ($unpinned_count rows)"
  exit 0
fi

if [ ! -f "$ALLOWLIST" ]; then
  echo "ERROR: $ALLOWLIST missing — generate it first:" >&2
  echo "  scripts/check-serial-uid-drift.sh --update-allowlist" >&2
  exit 2
fi

# comm needs both sides sorted the same way
VIOLATIONS="$(comm -23 <(sort -u "$unpinned_tmp") <(grep -vE '^#|^$' "$ALLOWLIST" | sort -u))"
if [ -n "$VIOLATIONS" ]; then
  echo "FAIL: new UNPINNED Serializable classes not in $ALLOWLIST:" >&2
  echo "$VIOLATIONS" >&2
  echo >&2
  echo "Either pin a deliberate serialVersionUID (see the Deck/ManaCostImpl/HumanPlayer pins)" >&2
  echo "or add an allowlist row with a justification comment — never by accident" >&2
  echo "." >&2
  exit 1
fi
echo "PASS phase 1: no unpinned Serializable classes outside the allowlist (${unpinned_count} files, oracle-inventoried)"

# ---- Phase 2: SUPERSEDED by check-save-uid-manifest.sh ----------------------------------------
# The old Phase 2 verified only the pins of classes CHANGED-vs-BASE. That cannot see a UID that
# drifts through a MERGE (the class arrives in a commit nobody edited), which is precisely how the
# replay corpus gets orphaned. scripts/check-save-uid-manifest.sh checks EVERY class that can reach
# a .game stream against a persisted UID manifest — a strict superset of "changed-vs-BASE" — so
# Phase 2 now delegates to it. --changed BASE is still accepted (BASE is ignored) so existing
# callers and hooks keep working.
if [ "$mode" = changed ]; then
  echo "Phase 2 superseded by check-save-uid-manifest.sh (strict superset: it covers every"
  echo "save-surface class, not just those changed vs ${changed_base}). Delegating."
  exec bash scripts/check-save-uid-manifest.sh
fi

echo "PASS: serial-uid check clean"
exit 0