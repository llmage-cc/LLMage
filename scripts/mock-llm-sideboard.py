#!/usr/bin/env python3
"""STRICT OpenAI-compatible mock provider — extends a strict-mock base
for the LLM-sideboard/postgame live test.

Base behavior (inherited): rejects ANY request whose body contains a top-level
"thinking" field with HTTP 400 (byte-equivalent to opencode zen/go for
glm-5.3-flash), serves /v1/models with context_length so non-Ollama detection
passes, logs every request.

EXTENSIONS for the live LLM-seat game (known gap in the base mock):
  - '=== SIDEBOARDING ==='  → 'NONE' (the sideboard parser Fail-Fasts on a
    non-format answer like the base 'MOCK'; 'NONE' is the documented
    no-changes answer and exercises sideboardNoChanges=true).
  - '=== POST-GAME REFLECTION ===' → short reflection text (postgame file
    body; the parser accepts any non-empty answer).
  - '=== REVISED GAMEPLAN FOR NEXT GAME ===' → short text.
  - '=== MATCH REVIEW FOR SIDEBOARDING ===' → short text.
  - '=== DECLARE ATTACKERS ===' / ATTACK DECLARATION → 'none' (base).
  - '=== DECLARE BLOCKERS ===' → 'none' (base).
  - '=== TARGET SELECTION ===' / '=== CARD SEARCH ===' / '=== LIBRARY SEARCH ==='
    / '=== LEGENDARY RULE ===' → '1' (first listed option; base fell through to
    'MOCK' which the numeric parser rejects).
  - '=== CHOOSE ONE ===' / 'CHOOSE MODE' / 'CHOOSE PILE' / 'CHOOSE AMOUNT' /
    'ANNOUNCE X' / 'CHOOSE REPLACEMENT EFFECT' / 'CHOOSE SPELL SIDE' /
    'ORDER TRIGGERS' / 'CARD NAME CHOICE' → '1' (safe first option).
  - '=== YES/NO DECISION ===' → 'no' (decline optional effects; safest default
    for a scripted game).
  - 'Choose N to M target(s)' fallback with 'Reply with ONLY' → '1'.

The action-loop branch (=== AVAILABLE ACTIONS ===) plays a land first, else a
cast, else an activation, else option 0 (pass) — never a skip control (skips
would fast-forward the game past the turn-count assertions of the driver).

Endpoint to point seats at: http://127.0.0.1:PORT/v1/chat/completions
Every request is appended to LOGDIR/mock-strict-PORT.log.
"""
import json
import os
import re
import sys
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer

LOGDIR = "/tmp/xmage-scratch"
LOGNAME = "mock-strict"

# ── Ask-reason verification: MOCK_REASON_SHAPES ──
# ADDITIVE, env-guarded — no effect unless MOCK_REASON_SHAPES is set.
#   1   = normal shape: answer line + "REASON: mock stated reason." second line
#   h1  = hostile #1: action-only answer, NO reason line (missing REASON)
#   h2  = hostile #2: "REASON:" as the FIRST line, real answer second
#   h3  = hostile #3: answer + reason line + trailing junk after it
#   h4  = hostile #4: answer + empty "REASON:" label (mangled/empty reason)
# Only applied to answer classes where a second line cannot confuse the parser
# (numeric/short-token decision classes + mulligan). Freeform reflection-class
# answers (reflection, revised gameplan, match review, deck assessment) stay
# single-line by design — their parsers accept any text and the wire shape is
# not what this leg verifies.
MOCK_REASON_MODE = os.environ.get("MOCK_REASON_SHAPES", "").strip()
# Ask-reason marker: env-guarded REASON-shape branch (unique to this mock)
_DUMP_DIR = None
_DUMP_SEQ = 0
_DUMP_LOCK = threading.Lock()


def reason_shaped(answer: str, prompt_class: str, text: str) -> str:
    """Return the answer transformed per MOCK_REASON_MODE (no-op when unset).

    Correction prompts ('Your previous answer was: ...') always get a plain,
    format-correct answer: the hostile shapes model an uncooperative FIRST
    attempt; the engine's existing correction path must recover the move.
    """
    if not MOCK_REASON_MODE:
        return answer
    if "Your previous answer was:" in text:
        return correction_answer(text)
    freeform = prompt_class in (
        "=== POST-GAME REFLECTION ===", "=== REVISED GAMEPLAN FOR NEXT GAME ===",
        "=== MATCH REVIEW FOR SIDEBOARDING ===", "PRE-GAME DECK ASSESSMENT",
        "=== SIDEBOARDING ===",
    )
    if freeform:
        return answer
    if MOCK_REASON_MODE == "h1":
        return answer  # action-only: REASON missing entirely
    if MOCK_REASON_MODE == "h2":
        # REASON label first, the real answer second — line 1 is NOT the
        # answer; the engine's correction path must recover the move.
        return "REASON: hostile first line with no answer\n" + answer
    if MOCK_REASON_MODE == "h3":
        return answer + "\nREASON: mock stated reason.\ntrailing junk that must be ignored"
    if MOCK_REASON_MODE == "h4":
        return answer + "\nREASON:"  # empty/mangled label — no reason captured
    return answer + "\nREASON: mock stated reason."


def correction_answer(text: str) -> str:
    """A format-correct answer inferred from the correction prompt's hint.

    The hint is generated by LLMPlayer.formatHintFor: e.g. 'a single number
    between 0 and 8 (0 = pass priority, ...)', '"keep" or "mulligan"', '"yes"
    or "no"', '"all", "none", or attack entries like "1->player"'. Ranged
    action numbers answer 0 (pass priority — always in range); other numeric
    classes answer 1 (first listed option)."""
    if '"keep" or "mulligan"' in text:
        return "keep"
    if '"yes" or "no"' in text:
        return "no"
    if '"all", "none", or attack entries' in text:
        return "none"
    if '"none" or block entries' in text:
        return "none"
    if '"1" or "2"' in text:
        return "1"
    if "single number between 0 and" in text:
        return "0"  # ranged action number: 0 = pass priority, always valid
    if "single number" in text or "comma-separated numbers" in text:
        return "1"  # simple number / comma numbers: first listed option
    return "0"  # last resort: pass priority


def maybe_dump_body(port: int, raw: bytes, prompt_class: str) -> None:
    """MOCK_DUMP_BODIES=1: append the raw request body to
    LOGDIR/bodies-<port>/<seq>-<class>.json (live prompt-body evidence)."""
    global _DUMP_DIR, _DUMP_SEQ
    if not os.environ.get("MOCK_DUMP_BODIES"):
        return
    with _DUMP_LOCK:
        if _DUMP_DIR is None:
            _DUMP_DIR = f"{LOGDIR}/bodies-{port}"
            os.makedirs(_DUMP_DIR, exist_ok=True)
        _DUMP_SEQ += 1
        cls = re.sub(r"[^A-Za-z0-9]+", "_", prompt_class).strip("_") or "OTHER"
        with open(f"{_DUMP_DIR}/{_DUMP_SEQ:04d}-{cls}.json", "wb") as f:
            f.write(raw)


def log_line(port: int, line: str) -> None:
    with open(f"{LOGDIR}/{LOGNAME}-{port}.log", "a") as f:
        f.write(line + "\n")


def pick_action(prompt: str) -> str:
    actions = {}
    collecting = False
    for ln in [x.strip() for x in prompt.splitlines()]:
        if ln.startswith("=== AVAILABLE ACTIONS ==="):
            collecting = True
            continue
        if collecting:
            m = re.match(r"^(\d+)\.\s+(.*)$", ln)
            if m:
                actions[int(m.group(1))] = m.group(2)
            elif ln.startswith("You are player:"):
                break
    for n, desc in sorted(actions.items()):
        if desc.lower().startswith("play land"):
            return str(n)
    for n, desc in sorted(actions.items()):
        if desc.lower().startswith("cast:"):
            return str(n)
    for n, desc in sorted(actions.items()):
        if desc.lower().startswith("activate"):
            return str(n)
    return "0"


def answer_for(body: dict) -> str:
    text = ""
    for msg in body.get("messages") or []:
        if msg.get("role") == "user":
            text = msg.get("content") or ""

    # --- live-test extensions (checked before the generic branches) ---
    if "=== SIDEBOARDING ===" in text:
        # The documented no-changes answer. The parser accepts NONE on the
        # first line (stripped of trailing punctuation) and skips the
        # IN:/OUT: parser, which would Fail-Fast on 'MOCK'.
        return "NONE"
    if "=== REVISED GAMEPLAN FOR NEXT GAME ===" in text:
        return "MOCK REVISED GAMEPLAN: hold the line, trade profitably, win game 2."
    if "=== POST-GAME REFLECTION ===" in text:
        # ── [REFLECTION-STALL] the earlier reflection run ──
        # MOCK_STALL_REFLECTION_SECONDS=N → hold this response N seconds before
        # answering, simulating the slow/hung provider on the game-over path

        # The sleep runs FIRST so the LLM call stays open while the match must
        # already be proceeding (sideboard / game 2). Default unset = instant
        # answer (current behavior). Self-contained on purpose: two sibling
        # units edit this file, so no top-of-file imports are added.
        _stall = __import__("os").environ.get("MOCK_STALL_REFLECTION_SECONDS", "")
        if _stall:
            print(f"[mock] REFLECTION-STALL: holding post-game reflection "
                  f"{_stall}s before answering", flush=True)
            __import__("time").sleep(float(_stall))
        # ── [/REFLECTION-STALL] ──
        return ("MOCK REFLECTION: Game played out with lands and creatures. "
                "I did well by developing my board; I could have attacked more. "
                "No technical issues observed. Engine experience 8/10. Fun: yes.")
    if "=== MATCH REVIEW FOR SIDEBOARDING ===" in text:
        return ("MOCK MATCH REVIEW: opponent played creatures and lands. "
                "No sideboard changes needed from my side.")
    # --- inherited base behavior ---
    if "PRE-GAME DECK ASSESSMENT" in text:
        return "MOCK GAMEPLAN: play lands, cast what you can, attack when profitable."
    if "MULLIGAN" in text.upper():
        return "keep"
    # Combat prompts have their own formats (blockers "1->2"/"none",
    # attackers "1->player"/"all"/"none") — a bare number crashes the parser.
    if "=== DECLARE BLOCKERS ===" in text:
        return "none"
    if "=== DECLARE ATTACKERS ===" in text or "ATTACK DECLARATION" in text:
        return "none"
    if "=== AVAILABLE ACTIONS ===" in text:
        return pick_action(text)
    if "=== YES/NO DECISION ===" in text:
        return "no"
    # Target/card selection prompts: reply with the first listed option.
    for header in ("=== TARGET SELECTION ===", "=== CARD SEARCH ===",
                   "=== LIBRARY SEARCH ===", "=== LEGENDARY RULE ===",
                   "=== CHOOSE ONE ===", "=== CHOOSE PILE ===",
                   "=== CHOOSE MODE ===", "=== CHOOSE AMOUNT ===",
                   "=== ANNOUNCE X ===", "=== CHOOSE REPLACEMENT EFFECT ===",
                   "=== CHOOSE SPELL SIDE ===", "=== ORDER TRIGGERS ===",
                   "=== CARD NAME CHOICE ===", "=== TARGET WITH AMOUNT ===",
                   "=== DISTRIBUTE AMOUNT ==="):
        if header in text:
            return "1"
    if "Reply with ONLY" in text or "Respond with ONLY" in text:
        return "1"
    return "MOCK"


class Handler(BaseHTTPRequestHandler):
    protocol_version = "HTTP/1.1"

    def _cors(self):
        self.send_header("Access-Control-Allow-Origin", "*")
        self.send_header("Access-Control-Allow-Methods", "GET, POST, OPTIONS")
        self.send_header("Access-Control-Allow-Headers",
                         "authorization,content-type,accept,x-opencode-session")

    def _json(self, code: int, payload: dict):
        data = json.dumps(payload).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(data)))
        self._cors()
        self.end_headers()
        self.wfile.write(data)

    def do_OPTIONS(self):
        log_line(self.server.server_port, "OPTIONS (preflight)")
        self.send_response(200)
        self.send_header("Content-Length", "0")
        self._cors()
        self.end_headers()

    def do_GET(self):
        auth = self.headers.get("Authorization")
        log_line(self.server.server_port,
                 f"GET {self.path} auth={'yes' if auth else 'no'}")
        if self.path.rstrip("/").endswith("/v1/models"):
            # id list is broad: the seat model id may vary (stub-model etc.), and
            # /v1/models matching is exact — include the ids the stage uses.
            self._json(200, {"object": "list", "data": [
                {"id": "mock-flash", "object": "model", "context_length": 131072},
                {"id": "stub-model", "object": "model", "context_length": 131072},
            ]})
        else:
            self._json(404, {"error": "not found"})

    def do_POST(self):
        length = int(self.headers.get("Content-Length") or 0)
        raw = self.rfile.read(length) if length else b""
        try:
            body = json.loads(raw.decode() or "{}")
        except Exception:
            body = {}
        has_thinking = "thinking" in body
        if has_thinking:
            log_line(self.server.server_port,
                     f"POST {self.path} REJECTED-400 thinking field present: "
                     f"{json.dumps(body.get('thinking'))} (model={body.get('model')})")
            self._json(400, {"error": {
                "param": "thinking",
                "type": "invalid_request_error",
                "message": 'invalid request body: json: unknown field "thinking"',
            }})
            return
        answer = answer_for(body)
        # identify the prompt class for the request log
        text = ""
        for msg in body.get("messages") or []:
            if msg.get("role") == "user":
                text = msg.get("content") or ""
        klass = next((h for h in (
            "=== SIDEBOARDING ===", "=== REVISED GAMEPLAN FOR NEXT GAME ===",
            "=== POST-GAME REFLECTION ===", "=== MATCH REVIEW FOR SIDEBOARDING ===",
            "PRE-GAME DECK ASSESSMENT", "=== MULLIGAN DECISION ===",
            "=== DECLARE ATTACKERS ===", "=== DECLARE BLOCKERS ===",
            "=== AVAILABLE ACTIONS ===", "=== YES/NO DECISION ===",
            "=== TARGET SELECTION ===",
        ) if h in text), "OTHER")
        # Ask-reason verification: env-guarded REASON-shape branch (MOCK_REASON_SHAPES)
        answer = reason_shaped(answer, klass, text)
        maybe_dump_body(self.server.server_port, raw, klass)
        log_line(self.server.server_port,
                 f"POST {self.path} has_thinking=no "
                 f"has_effort={'yes' if 'reasoning_effort' in body else 'no'} "
                 f"stream={body.get('stream')} chars={len(raw)} "
                 f"prompt_class={klass} reason_shape={MOCK_REASON_MODE or 'off'} "
                 f"has_suffix={'yes' if 'After your answer line' in text else 'no'} "
                 f"is_correction={'yes' if 'Your previous answer was:' in text else 'no'} "
                 f"answer={answer[:60]!r}")
        if body.get("stream"):
            self._sse(answer)
        else:
            self._json(200, {
                "id": "chatcmpl-strictmock",
                "object": "chat.completion",
                "model": body.get("model", "mock-flash"),
                "choices": [{"index": 0, "finish_reason": "stop",
                             "message": {"role": "assistant", "content": answer}}],
                "usage": {"prompt_tokens": 100, "completion_tokens": 5,
                          "total_tokens": 105},
            })

    def _sse(self, answer: str):
        """SSE stream matching the engine's parser: 'data: ' lines + [DONE]."""
        self.send_response(200)
        self.send_header("Content-Type", "text/event-stream")
        self.send_header("Cache-Control", "no-cache")
        self.send_header("Connection", "close")
        self.end_headers()

        def chunk(payload: dict):
            self.wfile.write(f"data: {json.dumps(payload)}\n\n".encode())
            self.wfile.flush()

        chunk({"choices": [{"index": 0, "delta": {"role": "assistant"}}]})
        chunk({"choices": [{"index": 0, "delta": {
            "reasoning_content": "Mock reasoning: assessing the position briefly."}}]})
        chunk({"choices": [{"index": 0, "delta": {"content": answer},
                            "finish_reason": "stop"}]})
        chunk({"choices": [], "usage": {"prompt_tokens": 100,
                                        "completion_tokens": 5, "total_tokens": 105}})
        self.wfile.write(b"data: [DONE]\n\n")
        self.wfile.flush()
        self.close_connection = True

    def log_message(self, fmt, *args):
        pass


def serve(port: int):
    srv = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    log_line(port, f"STRICT mock listening on {port} (rejects thinking field)")
    srv.serve_forever()


if __name__ == "__main__":
    ports = [int(p) for p in (sys.argv[1:] or ["18080"])]
    for p in ports[1:]:
        threading.Thread(target=serve, args=(p,), daemon=True).start()
    serve(ports[0])
